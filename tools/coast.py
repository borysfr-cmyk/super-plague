# Builds js/geo.js: Natural Earth 110m land outlines, warped so each continent sits under its region node.
# Usage: python3 tools/coast.py ne_110m_land.geojson
# (download: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson)
# Anchors: (lon, lat) of each region's real centre -> its (x, y) in js/data.js.
import json, numpy as np, sys
anch={'na':(-100,45,190,150),'sa':(-60,-15,290,340),'eu':(15,50,480,120),'ru':(75,58,650,90),'me':(45,28,580,215),
'af':(20,5,480,330),'sas':(78,22,700,250),'ea':(115,35,830,150),'sea':(110,5,820,300),'oc':(140,-25,910,410)}
A=np.array([v for v in anch.values()],float); ids=list(anch)
# linear fit
X=np.c_[A[:,0],np.ones(len(A))]; ax=np.linalg.lstsq(X,A[:,2],rcond=None)[0]
Y=np.c_[A[:,1],np.ones(len(A))]; ay=np.linalg.lstsq(Y,A[:,3],rcond=None)[0]
def lin(lon,lat): return ax[0]*lon+ax[1], ay[0]*lat+ay[1]
lx,ly=lin(A[:,0],A[:,1]); res=np.c_[A[:,2]-lx,A[:,3]-ly]
def proj(pts):
  pts=np.asarray(pts,float); x,y=lin(pts[:,0],pts[:,1])
  ll=pts[:,None,:]; d=np.hypot(ll[...,0]-A[None,:,0],ll[...,1]-A[None,:,1])+8
  w=1/d**2; w/=w.sum(1,keepdims=True); off=w@res
  return np.c_[x+off[:,0],y+off[:,1]]
gj=json.load(open(sys.argv[1]))
polys=[]
for f in gj['features']:
  g=f['geometry']; cs=g['coordinates'] if g['type']=='MultiPolygon' else [g['coordinates']]
  for p in cs:
    ring=np.array(p[0])
    if ring[:,1].max()<-55: continue
    # densify for smooth warp
    dense=[]
    for i in range(len(ring)-1):
      a,b=ring[i],ring[i+1]; n=max(1,int(np.hypot(*(b-a))/2))
      for t in range(n): dense.append(a+(b-a)*t/n)
    polys.append(proj(dense))
def path(p):
  p=p[::2]; return 'M'+'L'.join(f'{a:.1f},{b:.1f}' for a,b in p)+'Z'
d=''.join(path(p) for p in polys if len(p)>6)
open('js/geo.js','w').write("// Coastlines (Natural Earth 110m land, public domain), warped so each continent sits under its region node.\n// Generated by tools/coast.py.\nexport const COAST = '"+d+"';\n")
print(len(d)//1024,'KB',file=sys.stderr)
